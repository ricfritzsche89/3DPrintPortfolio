import 'dart:io';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:image_picker/image_picker.dart';
import 'package:provider/provider.dart';
import '../models/eintrag.dart';
import '../services/firebase_service.dart';

class EditEintragScreen extends StatefulWidget {
  final Eintrag? eintrag;

  const EditEintragScreen({super.key, this.eintrag});

  bool get isEditing => eintrag != null;

  @override
  State<EditEintragScreen> createState() => _EditEintragScreenState();
}

class _EditEintragScreenState extends State<EditEintragScreen> {
  final _formKey = GlobalKey<FormState>();
  late TextEditingController _titelController;
  late TextEditingController _beschreibungController;
  late TextEditingController _kategorieController;
  late TextEditingController _preisController;

  File? _imageFile;
  bool _isLoading = false;

  @override
  void initState() {
    super.initState();
    _titelController = TextEditingController(text: widget.eintrag?.titel ?? '');
    _beschreibungController = TextEditingController(text: widget.eintrag?.beschreibung ?? '');
    _kategorieController = TextEditingController(text: widget.eintrag?.kategorie ?? '');
    _preisController = TextEditingController(text: widget.eintrag?.preis?.toString() ?? '');
  }

  @override
  void dispose() {
    _titelController.dispose();
    _beschreibungController.dispose();
    _kategorieController.dispose();
    _preisController.dispose();
    super.dispose();
  }

  Future<void> _pickImage() async {
    final pickedFile = await ImagePicker().pickImage(source: ImageSource.gallery);
    if (pickedFile != null) {
      setState(() {
        _imageFile = File(pickedFile.path);
      });
    }
  }

  Future<void> _saveForm() async {
    if (_formKey.currentState!.validate()) {
      if (_imageFile == null && !widget.isEditing) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('Bitte wählen Sie ein Bild aus.')),
        );
        return;
      }

      setState(() { _isLoading = true; });

      final firebaseService = context.read<FirebaseService>();
      // Ersetze Komma durch Punkt für double.tryParse
      final preisText = _preisController.text.replaceAll(',', '.');
      final preis = preisText.isNotEmpty ? double.tryParse(preisText) : null;

      try {
        if (widget.isEditing) {
          final updatedEintrag = Eintrag(
            id: widget.eintrag!.id,
            titel: _titelController.text,
            beschreibung: _beschreibungController.text,
            kategorie: _kategorieController.text,
            preis: preis,
            bildUrl: widget.eintrag!.bildUrl, // Old URL is placeholder
            erstelltAm: widget.eintrag!.erstelltAm,
          );
          await firebaseService.updateEintrag(updatedEintrag, newImageFile: _imageFile);
        } else {
          final newEintrag = Eintrag(
            id: '', // Will be generated by Firestore
            titel: _titelController.text,
            beschreibung: _beschreibungController.text,
            kategorie: _kategorieController.text,
            preis: preis,
            bildUrl: '', // Will be generated by service
            erstelltAm: DateTime.now(),
          );
          await firebaseService.addEintrag(newEintrag, _imageFile!);
        }

        if (mounted) {
          Navigator.of(context).pop();
        }
      } catch (e) {
        if (mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('Fehler beim Speichern: $e')),
          );
        }
      } finally {
        if (mounted) {
          setState(() { _isLoading = false; });
        }
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Text(widget.isEditing ? 'Eintrag bearbeiten' : 'Neuer Eintrag'),
        actions: [
          if (_isLoading)
            const Padding(
              padding: EdgeInsets.all(8.0),
              child: Center(child: CircularProgressIndicator(color: Colors.white)),
            )
          else
            IconButton(
              icon: const Icon(Icons.save),
              onPressed: _saveForm,
            ),
        ],
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(16.0),
        child: Form(
          key: _formKey,
          child: Column(
            children: [
              // Image Preview
              _buildImagePreview(),
              const SizedBox(height: 16),
              ElevatedButton.icon(
                onPressed: _pickImage,
                icon: const Icon(Icons.image),
                label: const Text('Bild auswählen'),
              ),
              const SizedBox(height: 16),
              TextFormField(
                controller: _titelController,
                decoration: const InputDecoration(labelText: 'Titel'),
                validator: (value) => value!.isEmpty ? 'Bitte Titel eingeben' : null,
              ),
              TextFormField(
                controller: _beschreibungController,
                decoration: const InputDecoration(labelText: 'Beschreibung'),
                maxLines: 5,
                validator: (value) => value!.isEmpty ? 'Bitte Beschreibung eingeben' : null,
              ),
              TextFormField(
                controller: _kategorieController,
                decoration: const InputDecoration(labelText: 'Kategorie'),
                validator: (value) => value!.isEmpty ? 'Bitte Kategorie eingeben' : null,
              ),
              TextFormField(
                controller: _preisController,
                decoration: const InputDecoration(labelText: 'Preis (optional)', hintText: 'z.B. 19.99'),
                keyboardType: const TextInputType.numberWithOptions(decimal: true),
                inputFormatters: [
                  FilteringTextInputFormatter.allow(RegExp(r'^\d*([.,])?\d{0,2}')),
                ],
                validator: (value) {
                  if (value == null || value.isEmpty) {
                    return null; // Optional, also ist leer in Ordnung
                  }
                  // Erlaube Komma und Punkt als Dezimaltrennzeichen
                  final preisText = value.replaceAll(',', '.');
                  if (double.tryParse(preisText) == null) {
                    return 'Bitte geben Sie eine gültige Zahl ein.';
                  }
                  return null;
                },
              ),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildImagePreview() {
    return AspectRatio(
      aspectRatio: 16 / 9,
      child: Container(
        decoration: BoxDecoration(
          border: Border.all(color: Colors.grey),
          borderRadius: BorderRadius.circular(8),
        ),
        child: ClipRRect(
          borderRadius: BorderRadius.circular(8),
          child: _imageFile != null
              ? Image.file(_imageFile!, fit: BoxFit.cover)
              : (widget.isEditing && widget.eintrag!.bildUrl.isNotEmpty)
                  ? Image.network(widget.eintrag!.bildUrl, fit: BoxFit.cover)
                  : const Center(child: Text('Kein Bild ausgewählt')),
        ),
      ),
    );
  }
}
